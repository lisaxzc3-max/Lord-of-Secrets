function prep(pts){
 var len=[0],t=0;
 for(var i=1;i<pts.length;i++){t+=Math.hypot(pts[i][0]-pts[i-1][0],pts[i][1]-pts[i-1][1]);len.push(t)}
 var closed=pts.length>2&&pts[0][0]===pts[pts.length-1][0]&&pts[0][1]===pts[pts.length-1][1];
 return{p:pts,c:len,L:t,closed:closed};
}
function at(r,s){
 var c=r.c,p=r.p,i=1;
 while(i<c.length-1&&c[i]<s)i++;
 var a=p[i-1],b=p[i],k=(s-c[i-1])/Math.max(1,c[i]-c[i-1]);k=Math.max(0,Math.min(1,k));
 return[a[0]+(b[0]-a[0])*k,a[1]+(b[1]-a[1])*k,b[0]-a[0]];
}

